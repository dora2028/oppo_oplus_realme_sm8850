"""
Wire the self-contained LZ4KDS feature into a kernel source tree.

Everything this script needs lives under lz4kds/ in this repository; no
upstream file in the repository is modified.  The script only edits the
*checked-out kernel tree* inside the CI workspace, and it is idempotent:
running it twice produces the same result.

What it does
------------
1. Copies lz4kds/src/*.c, lz4kds/include/*.h into drivers/block/zram/ and
   include/linux/.
2. Appends the two new objects to drivers/block/zram/Makefile.
3. Adds `&backend_lz4kds` to the zram backend table in zcomp.c.
4. Adds the `release` callback to struct zcomp_ops in zcomp.h and calls it
   from zram_free_page() in zram_drv.c (used only for usage accounting).
5. Registers CONFIG_ZRAM_BACKEND_LZ4KDS in Kconfig.

Usage: lz4kds_inject.py <kernel-common-dir> <repo-lz4kds-dir>
"""
import os
import re
import shutil
import sys

MARK_BEGIN = "/* >>> lz4kds: injected, do not edit (generated by lz4kds_inject.py) */"
MARK_END = "/* <<< lz4kds: end */"

NEW_SOURCES = ["lz4kds_sddc.c", "lz4kds_backend.c"]
NEW_HEADERS = ["lz4kds_sddc.h", "lz4kds_zcomp.h"]
CODEC_SOURCES = [
    "lz4kd_encode.c",
    "lz4kd_encode_delta.c",
    "lz4kd_decode.c",
    "lz4kd_decode_delta.c",
]
CODEC_PRIVATE = [
    "lz4kd_private.h",
    "lz4kd_encode_private.h",
]
CODEC_PUBLIC = ["lz4kd.h"]


def die(msg):
    print("lz4kds_inject: ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def read(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def write(path, text):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def copy_files(root, repo):
    zram = os.path.join(root, "drivers/block/zram")
    inc = os.path.join(root, "include/linux")
    for d in (zram, inc):
        if not os.path.isdir(d):
            die("missing directory: " + d)

    copied = 0
    for name in NEW_SOURCES + CODEC_SOURCES + CODEC_PRIVATE:
        src = os.path.join(repo, "src", name)
        if not os.path.isfile(src):
            die("missing source: " + src)
        shutil.copyfile(src, os.path.join(zram, name))
        copied += 1
    # Private headers live next to the sources so quoted includes resolve.
    for name in NEW_HEADERS:
        src = os.path.join(repo, "include", name)
        if not os.path.isfile(src):
            die("missing header: " + src)
        shutil.copyfile(src, os.path.join(zram, name))
        copied += 1
    # The codec's public header is consumed as <linux/lz4kd.h>.
    for name in CODEC_PUBLIC:
        src = os.path.join(repo, "include", name)
        if not os.path.isfile(src):
            die("missing header: " + src)
        shutil.copyfile(src, os.path.join(inc, name))
        copied += 1
    print("lz4kds_inject: copied %d files" % copied)


def patch_makefile(root):
    path = os.path.join(root, "drivers/block/zram/Makefile")
    text = read(path)
    if "lz4kds_backend.o" in text:
        print("lz4kds_inject: Makefile already patched")
        return
    text += (
        "\n# LZ4KDS: self-contained backend (see lz4kds/ in the build repo)\n"
        "zram-$(CONFIG_ZRAM_BACKEND_LZ4KDS)\t+= lz4kds_backend.o lz4kds_sddc.o\n"
        "zram-$(CONFIG_ZRAM_BACKEND_LZ4KDS)\t+= lz4kd_encode.o lz4kd_encode_delta.o\n"
        "zram-$(CONFIG_ZRAM_BACKEND_LZ4KDS)\t+= lz4kd_decode.o lz4kd_decode_delta.o\n"
        "ccflags-$(CONFIG_ZRAM_BACKEND_LZ4KDS)\t+= -DLZ4K_DELTA\n"
    )
    write(path, text)
    print("lz4kds_inject: Makefile patched")


def patch_zcomp_c(root):
    path = os.path.join(root, "drivers/block/zram/zcomp.c")
    text = read(path)
    if "backend_lz4kds" in text:
        print("lz4kds_inject: zcomp.c already patched")
        return

    if '#include "backend_842.h"' in text:
        text = text.replace(
            '#include "backend_842.h"',
            '#include "backend_842.h"\n#include "lz4kds_backend_decl.h"',
            1,
        )
    else:
        die("cannot find include anchor in zcomp.c")

    m = re.search(r"(static const struct zcomp_ops \*backends\[\] = \{.*?)(\n\tNULL)",
                  text, re.S)
    if not m:
        die("cannot find backend table in zcomp.c")
    text = (text[:m.end(1)]
            + "\n#if IS_ENABLED(CONFIG_ZRAM_BACKEND_LZ4KDS)\n\t&backend_lz4kds,\n#endif"
            + m.group(2)
            + text[m.end(2):])
    write(path, text)
    print("lz4kds_inject: zcomp.c patched")


def patch_zcomp_h(root):
    path = os.path.join(root, "drivers/block/zram/zcomp.h")
    text = read(path)
    if "lz4kds_release" in text:
        print("lz4kds_inject: zcomp.h already patched")
        return
    anchor = "\tvoid (*release_params)(struct zcomp_params *params);\n"
    if anchor not in text:
        die("cannot find release_params in zcomp.h")
    add = anchor + (
        "\t/* LZ4KDS: optional hook, see zram_free_page() */\n"
        "\tvoid (*lz4kds_release)(struct zcomp_params *params,\n"
        "\t\t\t      const void *src, unsigned int src_len);\n"
    )
    write(path, text.replace(anchor, add, 1))
    print("lz4kds_inject: zcomp.h patched")


def patch_zram_drv_c(root):
    path = os.path.join(root, "drivers/block/zram/zram_drv.c")
    text = read(path)
    if "lz4kds_release" in text:
        print("lz4kds_inject: zram_drv.c already patched")
        return

    old = ("\thandle = zram_get_handle(zram, index);\n"
           "\tif (!handle)\n"
           "\t\treturn;\n"
           "\n"
           "\tzs_free(zram->mem_pool, handle);\n")
    if old not in text:
        die("cannot find free path anchor in zram_drv.c")
    new = ("\thandle = zram_get_handle(zram, index);\n"
           "\tif (!handle)\n"
           "\t\treturn;\n"
           "\n"
           + MARK_BEGIN + "\n"
           "\t{\n"
           "\t\tstruct zcomp *lc = zram->comps[ZRAM_PRIMARY_COMP];\n"
           "\n"
           "\t\tif (lc && lc->ops->lz4kds_release) {\n"
           "\t\t\tstruct zcomp_strm *ls = zcomp_stream_get(lc);\n"
           "\t\t\tvoid *lp = zs_map_object(zram->mem_pool, handle,\n"
           "\t\t\t\t\t\t ZS_MM_RO);\n"
           "\n"
           "\t\t\tlc->ops->lz4kds_release(lc->params, lp,\n"
           "\t\t\t\t\t\tzram_get_obj_size(zram, index));\n"
           "\t\t\tzs_unmap_object(zram->mem_pool, handle);\n"
           "\t\t\tzcomp_stream_put(lc);\n"
           "\t\t}\n"
           "\t}\n"
           + MARK_END + "\n"
           "\n"
           "\tzs_free(zram->mem_pool, handle);\n")
    write(path, text.replace(old, new, 1))
    print("lz4kds_inject: zram_drv.c patched")


def patch_kconfig(root):
    path = os.path.join(root, "drivers/block/zram/Kconfig")
    text = read(path)
    if "ZRAM_BACKEND_LZ4KDS" in text:
        print("lz4kds_inject: Kconfig already patched")
        return
    anchor = "config ZRAM_BACKEND_ZSTD"
    if anchor not in text:
        die("cannot find ZSTD anchor in Kconfig")
    block = (
        "config ZRAM_BACKEND_LZ4KDS\n"
        "\tbool \"lz4kds (LZ4KD + SDDC) compression support\"\n"
        "\tdepends on ZRAM\n"
        "\tselect LZ4KD_COMPRESS\n"
        "\tselect LZ4KD_DECOMPRESS\n"
        "\thelp\n"
        "\t  LZ4KD plus SDDC similarity/delta compression: identical pages\n"
        "\t  are stored once as an alias, and pages that differ in only a few\n"
        "\t  bytes are stored as a delta against a resident reference.  Pages\n"
        "\t  matching nothing fall back to plain single-page LZ4KD.\n"
        "\n"
    )
    write(path, text.replace(anchor, block + anchor, 1))
    print("lz4kds_inject: Kconfig patched")


def main():
    if len(sys.argv) != 3:
        die("usage: lz4kds_inject.py <kernel-common-dir> <repo-lz4kds-dir>")
    root, repo = sys.argv[1], sys.argv[2]
    if not os.path.isdir(root):
        die("kernel tree not found: " + root)
    if not os.path.isdir(repo):
        die("lz4kds dir not found: " + repo)

    copy_files(root, repo)

    # Small declaration header so zcomp.c can see the backend symbol.
    decl = os.path.join(root, "drivers/block/zram/lz4kds_backend_decl.h")
    write(decl,
          "/* SPDX-License-Identifier: GPL-2.0-or-later */\n"
          "#ifndef _LZ4KDS_BACKEND_DECL_H\n"
          "#define _LZ4KDS_BACKEND_DECL_H\n"
          "#if IS_ENABLED(CONFIG_ZRAM_BACKEND_LZ4KDS)\n"
          "extern const struct zcomp_ops backend_lz4kds;\n"
          "#endif\n"
          "#endif\n")

    patch_makefile(root)
    patch_zcomp_c(root)
    patch_zcomp_h(root)
    patch_zram_drv_c(root)
    patch_kconfig(root)
    print("lz4kds_inject: done")


if __name__ == "__main__":
    main()
